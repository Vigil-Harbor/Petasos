"""Write reference pages from the configuration, registry and command parser."""

from __future__ import annotations

import argparse
import json
from collections.abc import Mapping
from dataclasses import fields
from pathlib import Path

from petasos.config.layers import LEVELS, ROLES, SETTING_HELP, SETTING_LABEL, Settings, contains
from petasos.config.schema import FieldInfo, describe, leaves
from petasos.config.sections import PetasosConfig
from petasos.hermes.commands import _parser, install_registered_cli
from petasos.scanners.registry import REGISTRY

ROOT = Path(__file__).resolve().parents[1]


def _plain(value: object) -> object:
    if isinstance(value, Mapping):
        return {key: _plain(item) for key, item in value.items()}
    if isinstance(value, tuple):
        return [_plain(item) for item in value]
    return value


def _cell(value: object) -> str:
    return (
        str(value)
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace("|", "&#124;")
        .replace("\n", " ")
    )


def _code(value: object) -> str:
    return "`" + _cell(json.dumps(_plain(value), ensure_ascii=False)) + "`"


def _header(title: str, source: str) -> list[str]:
    return [
        f"# {title}",
        "",
        f"Generated by `scripts/generate_reference.py` from {source}. Do not edit by hand.",
        "Regenerate with `python -m scripts.generate_reference`.",
        "",
    ]


def settings_page() -> str:
    """Every described section and leaf, including display metadata and bounds."""
    lines = _header(
        "Settings reference",
        "`petasos.config.schema.describe(PetasosConfig)` and `petasos.config.layers.Settings`",
    )
    lines += [
        "## Stored settings",
        "",
        "| Path | Label | Help | Type | Default | Choices (value: label) | Restart |",
        "|---|---|---|---|---|---|---|",
    ]
    defaults = Settings()
    types = {"enabled": "bool", "role": "choice", "level": "choice", "overrides": "mapping"}
    for item in fields(Settings):
        name = item.name
        options = ROLES if name == "role" else LEVELS if name == "level" else {}
        choices = "; ".join(f"`{key}`: {_cell(value.label)}" for key, value in options.items())
        lines.append(
            f"| `{name}` | {SETTING_LABEL[name]} | {_cell(SETTING_HELP[name])} | {types[name]} | "
            f"{_code(getattr(defaults, name))} | {choices or '—'} | No |"
        )
    lines += [
        "",
        "## Resolved tree",
        "",
        "Defaults below belong to the tree before jobs, strictness and overrides are applied.",
        "",
    ]
    for row in describe(PetasosConfig):
        lines += [f"### `{row.path}` — {_cell(row.label)}", "", _cell(row.help), ""]
        if not isinstance(row, FieldInfo):
            lines += [
                f"Section. Audience: {row.audience}. Restart: {'Yes' if row.restart else 'No'}.",
                "",
            ]
            continue
        bounds = ", ".join(
            f"{key}={value:g}"
            for key in ("ge", "gt", "le", "lt")
            if (value := getattr(row, key)) is not None
        )
        lines += [
            "| Type | Default | Nullable | Restart | Audience | Bounds |",
            "|---|---|---|---|---|---|",
            f"| `{row.type_name}` | {_code(row.default)} | {'Yes' if row.nullable else 'No'} | "
            f"{'Yes' if row.restart else 'No'} | {row.audience} | {bounds or '—'} |",
            "",
        ]
        if row.choices is not None:
            lines += ["| Choice | Label |", "|---|---|"]
            for choice in row.choices:
                label = (row.choice_labels or {}).get(str(choice), str(choice))
                lines.append(f"| {_code(choice)} | {_cell(label)} |")
            lines.append("")
        if row.entry_labels is not None:
            lines += [
                f"Entry labels: {_cell(row.entry_labels[0])}; {_cell(row.entry_labels[1])}.",
                "",
            ]
    return "\n".join(lines)


def _at(document: Mapping[str, object], path: str) -> object:
    current: object = document
    for part in path.split("."):
        if not isinstance(current, Mapping):
            raise ValueError(path)
        current = current[part]
    return current


def layers_page() -> str:
    """Show exactly the partial document each job and strictness sets."""
    lines = _header(
        "Jobs and strictness reference", "`ROLES` and `LEVELS` in `petasos.config.layers`"
    )
    for title, table in (("Jobs (`role`)", ROLES), ("Strictness (`level`)", LEVELS)):
        lines += [f"## {title}", ""]
        for name, layer in table.items():
            lines += [f"### {layer.label} (`{name}`)", "", layer.description, ""]
            if name in ROLES and table is ROLES:
                lines += [
                    f"Suggested strictness: `{ROLES[name].suggests}`. "
                    "It is not applied automatically.",
                    "",
                ]
            lines += ["| Setting | Value set by this layer |", "|---|---|"]
            for row in leaves(PetasosConfig):
                if contains(layer.document, row.path):
                    lines.append(f"| `{row.path}` | {_code(_at(layer.document, row.path))} |")
            lines.append("")
    return "\n".join(lines)


def scanners_page() -> str:
    """Describe optional checks without constructing or probing a backend."""
    lines = _header("Scanner reference", "`petasos.scanners.registry.REGISTRY`")
    lines += [
        "The registry lists optional backends. "
        "The pipeline also runs its built-in syntactic scanner.",
        "",
        "| Id | Label | Purpose | Looks for | Extra | Default enablement |",
        "|---|---|---|---|---|---|",
    ]
    for spec in REGISTRY:
        lines.append(
            f"| `{spec.id}` | {_cell(spec.label)} | {_cell(spec.purpose)} | "
            f"{', '.join(sorted(spec.detects))} | {_code(spec.extra)} | `{spec.default_enabled}` |"
        )
    lines += [
        "",
        "Capabilities are the registry's terms: "
        "injection, personal information (`pii`), and code.",
        "",
    ]
    return "\n".join(lines)


def _help_formatter(prog: str) -> argparse.HelpFormatter:
    return argparse.HelpFormatter(prog, width=88)


def _commands(parser: argparse.ArgumentParser, help_text: str = "") -> list[str]:
    parser.formatter_class = _help_formatter
    lines = [f"## `{parser.prog}`", ""]
    if help_text:
        lines += [help_text, ""]
    lines += ["```text", parser.format_help().rstrip(), "```", ""]
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            helps = {item.dest: str(item.help) for item in action._choices_actions}
            for name, child in action.choices.items():
                lines += _commands(child, helps.get(name, ""))
    return lines


def commands_page() -> str:
    """Include every command, argument and help sentence from both CLI parsers."""
    lines = _header(
        "Command reference",
        "the argument parsers in `petasos.hermes.commands` "
        "(`_parser` and `install_registered_cli`)",
    )
    lines += _commands(_parser())
    registered = argparse.ArgumentParser(prog="hermes petasos")
    install_registered_cli(registered)
    lines += _commands(registered)
    return "\n".join(lines)


def write_reference(output: Path) -> None:
    """Write the complete generated reference under ``output``."""
    output.mkdir(parents=True, exist_ok=True)
    for name, content in (
        ("settings.md", settings_page()),
        ("layers.md", layers_page()),
        ("scanners.md", scanners_page()),
        ("commands.md", commands_page()),
    ):
        (output / name).write_text(content, encoding="utf-8")


def main() -> None:
    """Generate into the repository, or into a supplied comparison directory."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "docs" / "reference")
    args = parser.parse_args()
    write_reference(args.output)


if __name__ == "__main__":
    main()
